function rocketPlantValidateConfig(Rocket)
%ROCKETPLANTVALIDATECONFIG Reject incomplete or inconsistent physical inputs.
    names = fieldnames(Rocket);
    for k = 1:numel(names)
        value = Rocket.(names{k});
        if strcmp(names{k},'Motor')
            validatePreparedMotor(value);
            continue;
        end
        assert(isa(value,'double') && isreal(value) && all(isfinite(value(:))), ...
            'RocketPlant:InvalidParameter','Rocket.%s must be finite real double.',names{k});
    end
    scalarNames = {'Ts','MaxStep','IgnitionTime','RailLength', ...
        'LaunchInclination','LaunchHeading','LaunchRoll','Latitude','Longitude', ...
        'AltitudeMSL','DryMass','DryCenterOfMassZ','ReferenceArea','ReferenceLength', ...
        'AeroEnabled','BodyRadius','NoseLength','NoseBaseRadius','NoseTipZ', ...
        'NoseCPFraction','FinNumber','FinRootChord','FinTipChord','FinSpan', ...
        'FinSweepLength','FinLeadingEdgeZ','FinCant','TailLength', ...
        'TailTopRadius','TailBottomRadius','TailTopZ', ...
        'DrogueLag','DrogueCdS','DrogueInflationTime','MainAltitudeAGL', ...
        'MainLag','MainCdS','MainInflationTime'};
    for k = 1:numel(scalarNames)
        assert(isscalar(Rocket.(scalarNames{k})), ...
            'RocketPlant:InvalidSize','Rocket.%s must be scalar.',scalarNames{k});
    end
    vectorNames = {'DryInertia','ThrustDirection', ...
        'ThrustOffset','NozzleGyration','AngularDamping', ...
        'DrogueAttachment','MainAttachment','IMUOffset'};
    for k = 1:numel(vectorNames)
        assert(isequal(size(Rocket.(vectorNames{k})),[3 1]), ...
            'RocketPlant:InvalidSize','Rocket.%s must be a 3-by-1 column.',vectorNames{k});
    end
    curveNames = {'AeroMach','AeroCdPowered','AeroCdCoast','WindAltitude'};
    for k = 1:numel(curveNames)
        assert(iscolumn(Rocket.(curveNames{k})) && numel(Rocket.(curveNames{k}))>=2, ...
            'RocketPlant:InvalidSize','Rocket.%s must be a column with at least two rows.',curveNames{k});
    end
    assert(abs(Rocket.Latitude)<=pi/2 && abs(Rocket.Longitude)<=pi);
    assert(Rocket.Ts>0 && Rocket.MaxStep>0 && Rocket.MaxStep<=Rocket.Ts);
    assert(Rocket.IgnitionTime>=0 && Rocket.RailLength>=0);
    assert(Rocket.LaunchInclination>0 && Rocket.LaunchInclination<=pi/2);
    assert(Rocket.DryMass>0 && all(Rocket.DryInertia>0));
    assert(Rocket.ReferenceArea>0 && Rocket.ReferenceLength>0);
    assert(all(Rocket.AngularDamping>=0));
    assert(Rocket.AeroEnabled==0 || Rocket.AeroEnabled==1);
    if isfield(Rocket,'UseCdLookup')
        assert(isscalar(Rocket.UseCdLookup) && any(Rocket.UseCdLookup==[0 1]), ...
            'RocketPlant:InvalidCdSource','UseCdLookup must be 0 (Mach curves) or 1 (Cd table).');
    end
    if isfield(Rocket,'MomentumModel')
        assert(isscalar(Rocket.MomentumModel) && any(Rocket.MomentumModel==[0 1]), ...
            'RocketPlant:InvalidMomentumModel','MomentumModel must be 0 (physical derivation) or 1 (RocketPy 1.13).');
        if Rocket.MomentumModel==1
            hardwareMass=Rocket.DryMass+Rocket.Motor.Properties.DryMass;
            dryReferenceZ=(Rocket.DryMass*Rocket.DryCenterOfMassZ + ...
                Rocket.Motor.Properties.DryMass*Rocket.Motor.Properties.DryCenterOfMassZ)/hardwareMass;
            assert(abs(dryReferenceZ)<1e-10 && norm(Rocket.ThrustOffset(1:2))<1e-10 && ...
                norm(Rocket.ThrustDirection(1:2))<1e-10 && Rocket.ThrustDirection(3)>0, ...
                'RocketPlant:RocketPyReference', ...
                'RocketPy mode requires O at combined dry CM and an axial nozzle/thrust direction.');
        end
    end
    if isfield(Rocket,'IncludeCoriolis')
        assert(isscalar(Rocket.IncludeCoriolis) && any(Rocket.IncludeCoriolis==[0 1]), ...
            'RocketPlant:InvalidCoriolis','IncludeCoriolis must be 0 or 1.');
    end
    assert(Rocket.BodyRadius>0 && ...
        abs(Rocket.ReferenceArea-pi*Rocket.BodyRadius^2)<1e-12);
    assert(Rocket.NoseLength>=0 && Rocket.NoseBaseRadius>=0 && ...
        Rocket.NoseCPFraction>=0 && Rocket.NoseCPFraction<=1);
    assert(Rocket.FinNumber>=3 && Rocket.FinNumber==fix(Rocket.FinNumber));
    assert(Rocket.FinRootChord>0 && Rocket.FinTipChord>=0 && Rocket.FinSpan>0);
    assert(abs(Rocket.FinCant)<pi/2);
    assert(Rocket.TailLength>=0 && Rocket.TailTopRadius>=0 && ...
        Rocket.TailBottomRadius>=0 && Rocket.TailTopRadius+Rocket.TailBottomRadius>0);
    n=size(Rocket.AeroSurfaceCP,1);
    assert(n>=1 && size(Rocket.AeroSurfaceCP,2)==3);
    surfaceNames={'AeroSurfaceArea','AeroSurfaceDiameter','AeroSurfaceCNa', ...
        'AeroFinPlanform','AeroFinLiftNumerator','AeroFinLiftMultiplier', ...
        'AeroRollForceScale','AeroRollDampScale','AeroSurfaceCant'};
    for k=1:numel(surfaceNames)
        assert(isequal(size(Rocket.(surfaceNames{k})),[n 1]), ...
            'RocketPlant:InvalidSize','Rocket.%s must match the CP row count.',surfaceNames{k});
    end
    assert(all(Rocket.AeroSurfaceArea>0) && all(Rocket.AeroSurfaceDiameter>0));
    % A narrowing tail has a negative normal-force slope: preserve its sign.
    assert(all(Rocket.AeroFinPlanform>=0) && all(Rocket.AeroFinLiftNumerator>=0) && ...
        all(Rocket.AeroFinLiftMultiplier>=0) && all(Rocket.AeroRollDampScale>=0));
    assert(norm(Rocket.ThrustDirection)>0 && all(Rocket.NozzleGyration>=0));
    assert(all(diff(Rocket.AeroMach)>0) && Rocket.AeroMach(1)==0);
    assert(numel(Rocket.AeroMach)==numel(Rocket.AeroCdPowered) && ...
        numel(Rocket.AeroMach)==numel(Rocket.AeroCdCoast));
    assert(all(Rocket.AeroCdPowered>=0) && all(Rocket.AeroCdCoast>=0));
    assert(all(diff(Rocket.WindAltitude)>0) && size(Rocket.WindNED,2)==3 && ...
        size(Rocket.WindNED,1)==numel(Rocket.WindAltitude));
    assert(Rocket.DrogueLag>=0 && Rocket.MainLag>=0 && Rocket.MainAltitudeAGL>=0);
    assert(Rocket.DrogueCdS>=0 && Rocket.MainCdS>=0);
    assert(Rocket.DrogueInflationTime>0 && Rocket.MainInflationTime>0);
end

function validatePreparedMotor(Motor)
% Reuse the motor's input checks and verify all cached quantities once at init.
assert(isstruct(Motor) && isscalar(Motor) && ...
    isequal(sort(fieldnames(Motor)),sort({'StaticFire';'Type';'Properties'})), ...
    'RocketPlant:InvalidMotor','Rocket.Motor must contain prepared motor inputs.');
staticFire=Motor.StaticFire;
properties=Motor.Properties;
assert(isstruct(staticFire) && isscalar(staticFire) && ...
    all(isfield(staticFire,{'Time','Thrust','FuelFraction','OxidizerFraction', ...
    'HasFuelMassProfile','HasOxidizerMassProfile'})), ...
    'RocketPlant:InvalidMotor','Static-fire data must be prepared before simulation.');
assert(isscalar(staticFire.HasFuelMassProfile) && ...
    any(staticFire.HasFuelMassProfile==[0 1]) && ...
    isscalar(staticFire.HasOxidizerMassProfile) && ...
    any(staticFire.HasOxidizerMassProfile==[0 1]), ...
    'RocketPlant:InvalidMotor','Mass-profile flags must be exactly zero or one.');
source=table(staticFire.Time,staticFire.Thrust,'VariableNames',{'time_s','thrust_N'});
if staticFire.HasFuelMassProfile==1
    source.fuel_mass_kg=properties.FuelResidualMass+staticFire.FuelFraction* ...
        (properties.FuelInitialMass-properties.FuelResidualMass);
    % Avoid subtraction/addition roundoff when reconstructing valid endpoints.
    assert(staticFire.FuelFraction(1)==double(properties.FuelInitialMass> ...
        properties.FuelResidualMass) && staticFire.FuelFraction(end)==0, ...
        'RocketPlant:InvalidMotor','Prepared fuel profile endpoints are invalid.');
    source.fuel_mass_kg([1 end])=[properties.FuelInitialMass;properties.FuelResidualMass];
end
if staticFire.HasOxidizerMassProfile==1
    source.oxidizer_mass_kg=properties.OxidizerResidualMass+staticFire.OxidizerFraction* ...
        (properties.OxidizerInitialMass-properties.OxidizerResidualMass);
    assert(staticFire.OxidizerFraction(1)==double(properties.OxidizerInitialMass> ...
        properties.OxidizerResidualMass) && staticFire.OxidizerFraction(end)==0, ...
        'RocketPlant:InvalidMotor','Prepared oxidizer profile endpoints are invalid.');
    source.oxidizer_mass_kg([1 end])=[properties.OxidizerInitialMass;properties.OxidizerResidualMass];
end
[expected,expectedType,expectedProperties]=rocketMotorPrepare(source,Motor.Type,properties);
assert(isequal(expectedType,Motor.Type) && isequal(expectedProperties,properties), ...
    'RocketPlant:InvalidMotor','Prepared motor type/properties are inconsistent.');
names=fieldnames(expected);
assert(isequal(sort(names),sort(fieldnames(staticFire))), ...
    'RocketPlant:InvalidMotor','Prepared motor data fields are inconsistent.');
% These caches are deterministic for the same time/thrust data. Exact checks
% also protect very small positive impulse curves from an absolute tolerance.
assert(isequal(staticFire.CumulativeImpulse,expected.CumulativeImpulse) && ...
    isequal(staticFire.TotalImpulse,expected.TotalImpulse), ...
    'RocketPlant:MotorCacheMismatch','Reprepare changed motor impulse data.');
for k=1:numel(names)
    actual=staticFire.(names{k}); reference=expected.(names{k});
    assert(isa(actual,'double') && isreal(actual) && all(isfinite(actual(:))) && ...
        isequal(size(actual),size(reference)) && ...
        all(abs(actual(:)-reference(:))<=1e-10*max(1,abs(reference(:)))), ...
        'RocketPlant:MotorCacheMismatch','Reprepare changed motor data; invalid field %s.',names{k});
end
end
