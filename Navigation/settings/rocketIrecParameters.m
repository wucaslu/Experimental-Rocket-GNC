function [RocketParameters,MotorProperties,MotorStaticFireSource,Info,MotorImportOptions] = rocketIrecParameters(dragSource,airfoilSource,physicalRailLength,burnOutTime,airfoilAngleUnit)
%ROCKETIRECPARAMETERS Prepare the supplied IREC rocket and Mandioca motor.
% INPUTS
%   dragSource: required numeric N-by-2 [Mach,Cd] matrix or filename holding
%       those two columns. The same measured curve is used powered/coasting.
%   airfoilSource: required numeric N-by-2 [angle,CL] matrix or filename
%       holding those two columns. Declare angle units with airfoilAngleUnit.
%   physicalRailLength: physical launch-rail length [m], greater than the
%       nozzle-to-upper-button distance. Default 5.2 m is a caller-editable
%       assumption until the actual rail length is supplied.
%   burnOutTime: time since ignition at the supplied motor cutoff [s].
%       Default 3.99 s matches the supplied RocketPy motor configuration.
%   airfoilAngleUnit: 'degrees' (default) or 'radians'. The original supplied
%       RocketPy configuration declared degrees; NACA0012-radians.csv stores
%       radians and must be selected with 'radians'. Units are never inferred
%       from a filename or numeric range. Only degree-valued inputs convert.
% OUTPUTS
%   RocketParameters: finite numeric overrides for rocketPlantSettings.
%       Positions use a fixed origin at the combined dry CM, +Z noseward.
%       Site, heading, inclination and launch roll are left to the caller.
%   MotorProperties: SI motor masses, intrinsic diagonal inertias, component
%       axial centers and enabled symmetric BATES grain geometry. Motor dry
%       mass/inertia are zero exactly as supplied; no hardware is added.
%   MotorStaticFireSource: adjacent unmodified mandioca_2024.csv filename.
%   Info: initialization-only provenance, source-coordinate audit, input
%       geometry and recovery details unsupported by the present plant.
%   MotorImportOptions: named CSV columns, explicit abrupt endpoint policy
%       and cutoff time for rocketMotorPrepare. No strings enter runtime.
% The initializer reads the requested aerodynamic sources once. It performs
% no model edits and retains no state. Mass comes from supplied grain volume
% and density; remaining-mass/inertia evolution uses the existing motor model.

assert(nargin>=2,'RocketIrec:MissingSources', ...
    'Supply drag [Mach,Cd] and airfoil [angle,CL] sources.');
railLengthDefaulted = nargin<3 || isempty(physicalRailLength);
if railLengthDefaulted, physicalRailLength=5.2; end
burnOutDefaulted = nargin<4 || isempty(burnOutTime);
if burnOutDefaulted, burnOutTime=3.99; end
if nargin<5, airfoilAngleUnit='degrees'; end
assert((ischar(airfoilAngleUnit) && isrow(airfoilAngleUnit)) || ...
    (isstring(airfoilAngleUnit) && isscalar(airfoilAngleUnit)), ...
    'RocketIrec:AirfoilAngleUnit','airfoilAngleUnit must be degrees or radians.');
airfoilAngleUnit=lower(char(airfoilAngleUnit));
assert(any(strcmp(airfoilAngleUnit,{'degrees','radians'})), ...
    'RocketIrec:AirfoilAngleUnit','airfoilAngleUnit must be degrees or radians.');
validateattributes(physicalRailLength,{'numeric'}, ...
    {'real','finite','scalar','positive'},mfilename,'physicalRailLength');
validateattributes(burnOutTime,{'numeric'}, ...
    {'real','finite','scalar','positive'},mfilename,'burnOutTime');
physicalRailLength=full(double(physicalRailLength));
burnOutTime=full(double(burnOutTime));
[drag,dragDescription]=readPairs(dragSource,'drag');
[airfoil,airfoilDescription]=readPairs(airfoilSource,'airfoil');
assert(all(drag(:,1)>=0) && all(drag(:,2)>=0), ...
    'RocketIrec:DragRange','Drag data must contain nonnegative Mach and Cd.');
if strcmp(airfoilAngleUnit,'degrees')
    airfoilAngleRad=deg2rad(airfoil(:,1));
else
    airfoilAngleRad=airfoil(:,1);
end
finLiftSlope=(airfoil(2,2)-airfoil(1,2)) / ...
    (airfoilAngleRad(2)-airfoilAngleRad(1));
assert(isfinite(finLiftSlope) && finLiftSlope>0, ...
    'RocketIrec:AirfoilSlope', ...
    'The first two airfoil samples must define a positive lift slope in the declared angle units.');
if drag(1,1)>0
    drag=[0,drag(1,2);drag];
end

% Supplied RocketPy rocket coordinates increase nose-to-tail. The motor's
% nozzle-to-chamber axis points noseward, opposite to the rocket source axis.
airframeMass=24.159;
airframeInertia=[13.7013;13.7016;0.1159];
dryCenterSource=1.7419;
motorInstallationSource=2.8777;
motorDryCenterLocal=0;
grainCenterLocal=0.532;
nozzleLocal=0;
motorDryCenterSource=motorInstallationSource-motorDryCenterLocal;
grainCenterSource=motorInstallationSource-grainCenterLocal;
nozzleSource=motorInstallationSource-nozzleLocal;
motorDryCenterZ=dryCenterSource-motorDryCenterSource;
grainCenterZ=dryCenterSource-grainCenterSource;
nozzleZ=dryCenterSource-nozzleSource;

grainCount=5;
grainDensity=1750.54;
grainOuterRadius=94/2000;
grainInitialInnerRadius=31.75/2000;
grainInitialHeight=15.135/100;
grainSeparation=0.009;
nozzleRadius=65/2000;
throatRadius=0.011;
grainVolume=pi*(grainOuterRadius^2-grainInitialInnerRadius^2)*grainInitialHeight;
grainMass=grainDensity*grainVolume;
propellantMass=grainCount*grainMass;
grainCenterOffsets=(-(grainCount-1)/2:(grainCount-1)/2).' * ...
    (grainInitialHeight+grainSeparation);
radiusSquaredSum=grainOuterRadius^2+grainInitialInnerRadius^2;
transverseInertia=propellantMass*(radiusSquaredSum/4+grainInitialHeight^2/12) + ...
    grainMass*sum(grainCenterOffsets.^2);
axialInertia=propellantMass*radiusSquaredSum/2;
propellantInertia=[transverseInertia;transverseInertia;axialInertia];

MotorProperties=struct('DryMass',0,'DryInertia',zeros(3,1), ...
    'FuelInitialMass',propellantMass,'FuelResidualMass',0, ...
    'OxidizerInitialMass',0,'OxidizerResidualMass',0, ...
    'FuelInitialInertia',propellantInertia,'FuelResidualInertia',zeros(3,1), ...
    'OxidizerInitialInertia',zeros(3,1),'OxidizerResidualInertia',zeros(3,1), ...
    'DryCenterOfMassZ',motorDryCenterZ, ...
    'FuelInitialCenterOfMassZ',grainCenterZ,'FuelResidualCenterOfMassZ',grainCenterZ, ...
    'OxidizerInitialCenterOfMassZ',0,'OxidizerResidualCenterOfMassZ',0, ...
    'GrainInertiaEnabled',1,'GrainCount',grainCount,'GrainDensity',grainDensity, ...
    'GrainOuterRadius',grainOuterRadius,'GrainInitialInnerRadius',grainInitialInnerRadius, ...
    'GrainInitialHeight',grainInitialHeight,'GrainSeparation',grainSeparation);

upperRailButtonSource=1.856;
lowerRailButtonSource=2.8115;
railExitOffset=abs(nozzleSource-upperRailButtonSource);
assert(physicalRailLength>railExitOffset,'RocketIrec:RailLength', ...
    'Physical rail length must exceed %.4f m nozzle-to-upper-button distance.',railExitOffset);
tailPositionSource=2.8367;
tailLength=0.052;
RocketParameters=struct();
RocketParameters.MomentumModel=1;
RocketParameters.IncludeCoriolis=1;
RocketParameters.DryMass=airframeMass;
RocketParameters.DryInertia=airframeInertia;
RocketParameters.DryCenterOfMassZ=0;
RocketParameters.ThrustDirection=[0;0;1];
RocketParameters.ThrustOffset=[0;0;nozzleZ];
RocketParameters.NozzleGyration=[(nozzleRadius^2+nozzleZ^2)/4; ...
    (nozzleRadius^2+nozzleZ^2)/4;nozzleRadius^2/2];
RocketParameters.BodyRadius=0.0858;
RocketParameters.ReferenceArea=pi*RocketParameters.BodyRadius^2;
RocketParameters.ReferenceLength=tailPositionSource+tailLength;
RocketParameters.RailLength=physicalRailLength-railExitOffset;
RocketParameters.AeroEnabled=1;
RocketParameters.UseCdLookup=0;
RocketParameters.CdLookupIsIncremental=0;
RocketParameters.AeroMach=drag(:,1);
RocketParameters.AeroCdPowered=drag(:,2);
RocketParameters.AeroCdCoast=drag(:,2);
RocketParameters.NoseLength=0.6113;
RocketParameters.NoseBaseRadius=RocketParameters.BodyRadius;
RocketParameters.NoseTipZ=dryCenterSource;
RocketParameters.NoseCPFraction=0.5;
RocketParameters.FinNumber=4;
RocketParameters.FinRootChord=0.175;
RocketParameters.FinTipChord=0.145;
RocketParameters.FinSpan=0.17;
RocketParameters.FinSweepLength=0.03;
RocketParameters.FinLeadingEdgeZ=dryCenterSource-2.6203;
RocketParameters.FinCant=deg2rad(0.5);
RocketParameters.FinLiftSlope2D=finLiftSlope;
RocketParameters.TailLength=tailLength;
RocketParameters.TailTopRadius=0.0858;
RocketParameters.TailBottomRadius=0.06536;
RocketParameters.TailTopZ=dryCenterSource-tailPositionSource;
RocketParameters.DrogueLag=1.5;
RocketParameters.DrogueCdS=1.215;
RocketParameters.MainAltitudeAGL=426;
RocketParameters.MainLag=1.5;
RocketParameters.MainCdS=6.575;

MotorStaticFireSource=fullfile(fileparts(mfilename('fullpath')), ...
    'mandioca_2024','mandioca_2024.csv');
assert(isfile(MotorStaticFireSource),'RocketIrec:MissingMotorCurve', ...
    'Missing supplied static-fire CSV: %s.',MotorStaticFireSource);
MotorImportOptions=struct('TimeColumn','burn_time', ...
    'ThrustColumn','thrust_corrected','EndpointMode','abrupt', ...
    'BurnOutTime',burnOutTime);

dryMass=airframeMass;
wetMass=dryMass+propellantMass;
wetCenterZ=propellantMass*grainCenterZ/wetMass;
wetCenterSource=dryCenterSource-wetCenterZ;
wetWholeInertia=airframeInertia+propellantInertia + ...
    [dryMass*wetCenterZ^2+propellantMass*(grainCenterZ-wetCenterZ)^2; ...
     dryMass*wetCenterZ^2+propellantMass*(grainCenterZ-wetCenterZ)^2;0];
recovery=struct('DrogueTrigger','apogee','DrogueCdS_M2',1.215, ...
    'MainTriggerAltitudeAGL_M',426,'MainCdS_M2',6.575, ...
    'SamplingRateHz',50,'LagS',1.5,'PressureNoiseMeanPa',0, ...
    'PressureNoiseStdPa',8.3,'PressureNoiseCorrelation',0.5);
Info=struct('ExampleName','Supplied IREC rocket / Mandioca solid motor', ...
    'Source','User-supplied RocketPy component configuration and static-fire data', ...
    'RocketSourceAxis','nose_to_tail','MotorSourceAxis','nozzle_to_chamber', ...
    'BodyOrigin','Combined dry center of mass; +Z noseward', ...
    'CoordinateRule','body_Z = dry_CM_source - rocket_source_position', ...
    'MotorCoordinateRule','rocket_source_position = motor_installation - motor_local_position', ...
    'DryCenterOfMassSourceM',dryCenterSource,'DryCenterOfMassAtOM',0, ...
    'WetCenterOfMassSourceM',wetCenterSource,'WetCenterOfMassAtOM',wetCenterZ, ...
    'MotorInstallationSourceM',motorInstallationSource, ...
    'MotorDryCenterSourceM',motorDryCenterSource,'MotorDryCenterAtOM',motorDryCenterZ, ...
    'PropellantCenterSourceM',grainCenterSource,'PropellantCenterAtOM',grainCenterZ, ...
    'NozzlePositionSourceM',nozzleSource,'NozzlePositionAtOM',nozzleZ, ...
    'NoseTipSourceM',0,'FinLeadingEdgeSourceM',2.6203,'TailTopSourceM',tailPositionSource, ...
    'PhysicalRailLengthM',physicalRailLength,'PhysicalRailLengthDefaulted',railLengthDefaulted, ...
    'EffectiveRailTravelM',RocketParameters.RailLength,'RailExitOffsetM',railExitOffset, ...
    'UpperRailButtonSourceM',upperRailButtonSource,'LowerRailButtonSourceM',lowerRailButtonSource, ...
    'UpperRailButtonAtOM',dryCenterSource-upperRailButtonSource, ...
    'LowerRailButtonAtOM',dryCenterSource-lowerRailButtonSource, ...
    'RailButtonAngularPositionRad',deg2rad(45),'MotorDryMassKg',0, ...
    'DryMassKg',dryMass,'WetMassKg',wetMass,'PropellantInitialMassKg',propellantMass, ...
    'PropellantInitialIntrinsicInertiaKgm2',propellantInertia, ...
    'DryWholeInertiaAtCM_Kgm2',airframeInertia,'WetWholeInertiaAtCM_Kgm2',wetWholeInertia, ...
    'GrainNumber',grainCount,'GrainDensityKgpm3',grainDensity, ...
    'GrainOuterRadiusM',grainOuterRadius,'GrainInitialInnerRadiusM',grainInitialInnerRadius, ...
    'GrainInitialHeightM',grainInitialHeight,'GrainSeparationM',grainSeparation, ...
    'GrainInitialVolumeM3',grainVolume,'GrainInitialMassKg',grainMass, ...
    'GrainCenterOffsetsM',grainCenterOffsets,'NozzleRadiusM',nozzleRadius, ...
    'ThroatRadiusM',throatRadius,'BurnDurationS',burnOutTime, ...
    'BurnOutTimeDefaulted',burnOutDefaulted,'FinLiftSlope2DPerRad',finLiftSlope, ...
    'AirfoilAngleUnit',airfoilAngleUnit,'RecoveryRequested',recovery, ...
    'SourceFiles',struct('StaticFire',MotorStaticFireSource,'Drag',dragDescription, ...
        'Airfoil',airfoilDescription), ...
    'Caveats',{{'Launch site, heading, inclination and roll are not specified by these component inputs; the caller supplies them.', ...
        'The rail model uses effective travel only; separate upper/lower button constraints and the 45 degree button orientation are not simulated.', ...
        'Recovery CdS, lag and altitude triggers are imported; the current deterministic plant does not reproduce 50 Hz noisy pressure-based RocketPy trigger sampling.', ...
        'Recovery inflation, attachment positions, and the IMU station remain caller settings because this component configuration does not specify them.', ...
        'The airfoil slope follows the first two samples in radians; degree-valued inputs convert once and radian-valued inputs are unchanged. Powered and coast drag both use the supplied curve.', ...
        'Zero motor dry mass/inertia follow the supplied inputs; any retained motor hardware must already be included in the supplied rocket dry properties.', ...
        'Throat radius is provenance only; static-fire replay does not simulate chamber pressure or nozzle flow.', ...
        'ReferenceLength is the tail-bottom source station measured from the nose tip; it is metadata, not an inferred aerodynamic force parameter.'}});
end

function [pairs,description]=readPairs(source,kind)
if isnumeric(source)
    pairs=source;
    description=['Numeric ',kind,' pair matrix'];
else
    assert((ischar(source) && isrow(source)) || ...
        (isstring(source) && isscalar(source)),'RocketIrec:SourceType', ...
        '%s source must be a two-column numeric matrix or one filename.',kind);
    description=char(source);
    assert(isfile(description),'RocketIrec:MissingSource', ...
        'Missing %s source: %s.',kind,description);
    pairs=readmatrix(description);
end
assert(isnumeric(pairs) && isreal(pairs) && ismatrix(pairs) && ...
    size(pairs,2)==2 && size(pairs,1)>=2 && all(isfinite(pairs(:))), ...
    'RocketIrec:PairData','%s source must contain finite real N-by-2 numeric pairs.',kind);
pairs=full(double(pairs));
assert(all(diff(pairs(:,1))>0),'RocketIrec:PairGrid', ...
    '%s source first column must increase strictly without duplicate entries.',kind);
end
