function [RocketParameters,MotorProperties,MotorStaticFireSource,Info] = rocketPyCalistoParameters()
%ROCKETPYCALISTOPARAMETERS Load the getting_started.ipynb rocket example.
% INPUTS
%   None. Published example values and adjacent rocketpy_calisto assets are
%   read once during initialization. No Simulink model is opened or changed.
% OUTPUTS
%   RocketParameters: finite double-valued rocket setting overrides in SI
%       units. Intrinsic airframe inertia is about its own CM; all axial body
%       positions use a fixed origin O at the combined rocket/motor dry CM.
%       Body +Z points toward the nose. AeroMach/AeroCdPowered/AeroCdCoast
%       are matched column vectors; the Mach-zero endpoint holds the first Cd.
%   MotorProperties: motor component masses [kg], intrinsic diagonal inertias
%       [3x1 kg*m^2], axial CM positions [m], and enabled numeric BATES grain
%       geometry, suitable for rocketMotorPrepare.
%   MotorStaticFireSource: CSV filename with time_s/thrust_N columns. Import
%       it with rocketMotorPrepare; no strings enter the motor runtime inputs.
%   Info: initialization-only provenance, notebook coordinates, raw grain
%       geometry and assumptions. This metadata is not a runtime Rocket field.
% The factory provides parameter overrides, not a complete runtime Rocket.
% Launch location/rail/attitude replay the executed notebook. Sensors, weather
% loading, integration and actuator settings remain supplied by the caller.
% It retains no state and does not predict grain combustion.

assetDirectory = fullfile(fileparts(mfilename('fullpath')),'rocketpy_calisto');
MotorStaticFireSource = fullfile(assetDirectory,'motor_static_fire.csv');
poweredSource = fullfile(assetDirectory,'powerOnDragCurve.csv');
coastSource = fullfile(assetDirectory,'powerOffDragCurve.csv');
airfoilSource = fullfile(assetDirectory,'NACA0012-radians.txt');
assert(isfile(MotorStaticFireSource),'RocketPyCalisto:MissingMotorCurve', ...
    'Missing converted static-fire CSV: %s.',MotorStaticFireSource);
powered = readDragCurve(poweredSource);
coast = readDragCurve(coastSource);
assert(isequal(powered(:,1),coast(:,1)), ...
    'RocketPyCalisto:DragGrid','Powered and coast drag curves must use the same Mach grid.');
assert(isfile(airfoilSource),'RocketPyCalisto:MissingAirfoil', ...
    'Missing example airfoil data: %s.',airfoilSource);
airfoil = readmatrix(airfoilSource,'Delimiter',',');
assert(isreal(airfoil) && size(airfoil,2)==2 && size(airfoil,1)>=2 && ...
    all(isfinite(airfoil(:))) && all(diff(airfoil(:,1))>0), ...
    'RocketPyCalisto:AirfoilData','Airfoil data must be finite increasing [angle_rad,CL] pairs.');
finLiftSlope = (airfoil(2,2)-airfoil(1,2))/(airfoil(2,1)-airfoil(1,1));
assert(isfinite(finLiftSlope) && finLiftSlope>0, ...
    'RocketPyCalisto:AirfoilSlope','The example airfoil must have a positive initial lift slope.');

% Notebook coordinates: airframe CM is zero; both rocket and motor axes point
% noseward, so the motor installation offset is added without a sign reversal.
airframeMass = 14.426;
airframeInertia = [6.321;6.321;0.034];
airframeCenter = 0;
motorDryMass = 1.815;
motorDryInertia = [0.125;0.125;0.002];
motorInstallation = -1.255;
motorDryCenterLocal = 0.317;
propellantCenterLocal = 0.397;
nozzleCenterLocal = 0;
nozzleRadius = 0.033;
throatRadius = 0.011;
motorDryCenter = motorInstallation+motorDryCenterLocal;
propellantCenter = motorInstallation+propellantCenterLocal;
nozzleCenter = motorInstallation+nozzleCenterLocal;
dryMass = airframeMass+motorDryMass;
dryCenterNotebook = (airframeMass*airframeCenter+motorDryMass*motorDryCenter)/dryMass;
coordinateShift = -dryCenterNotebook;

% Annular-cylinder BATES stack, including fixed spacing between grain centers.
grainNumber = 5;
grainDensity = 1815;
grainOuterRadius = 0.033;
grainInitialInnerRadius = 0.015;
grainInitialHeight = 0.120;
grainSeparation = 0.005;
grainVolume = pi*(grainOuterRadius^2-grainInitialInnerRadius^2)*grainInitialHeight;
grainMass = grainDensity*grainVolume;
propellantMass = grainNumber*grainMass;
grainCenterOffsets = ((-(grainNumber-1)/2):((grainNumber-1)/2)).' * ...
    (grainInitialHeight+grainSeparation);
radiusSquaredSum = grainOuterRadius^2+grainInitialInnerRadius^2;
propellantTransverseInertia = propellantMass*(radiusSquaredSum/4+grainInitialHeight^2/12) + ...
    grainMass*sum(grainCenterOffsets.^2);
propellantAxialInertia = propellantMass*radiusSquaredSum/2;
propellantInertia = [propellantTransverseInertia;propellantTransverseInertia;propellantAxialInertia];

MotorProperties = struct('DryMass',motorDryMass,'DryInertia',motorDryInertia, ...
    'FuelInitialMass',propellantMass,'FuelResidualMass',0, ...
    'OxidizerInitialMass',0,'OxidizerResidualMass',0, ...
    'FuelInitialInertia',propellantInertia,'FuelResidualInertia',zeros(3,1), ...
    'OxidizerInitialInertia',zeros(3,1),'OxidizerResidualInertia',zeros(3,1), ...
    'DryCenterOfMassZ',motorDryCenter+coordinateShift, ...
    'FuelInitialCenterOfMassZ',propellantCenter+coordinateShift, ...
    'FuelResidualCenterOfMassZ',propellantCenter+coordinateShift, ...
    'OxidizerInitialCenterOfMassZ',0,'OxidizerResidualCenterOfMassZ',0, ...
    'GrainInertiaEnabled',1,'GrainCount',grainNumber,'GrainDensity',grainDensity, ...
    'GrainOuterRadius',grainOuterRadius,'GrainInitialInnerRadius',grainInitialInnerRadius, ...
    'GrainInitialHeight',grainInitialHeight,'GrainSeparation',grainSeparation);

RocketParameters = struct();
RocketParameters.MomentumModel = 1; % native RocketPy 1.13 comparison
RocketParameters.IncludeCoriolis = 1;
% Use the actual elevation returned by the executed notebook's GFS model,
% which replaced the notebook's initially requested 1400 m elevation.
weatherSource = jsondecode(fileread(fullfile(assetDirectory,'weather_notebook_gfs.json')));
RocketParameters.Latitude = deg2rad(weatherSource.LatitudeDeg);
RocketParameters.Longitude = deg2rad(weatherSource.LongitudeDeg);
RocketParameters.AltitudeMSL = weatherSource.ElevationM;
RocketParameters.LaunchHeading = deg2rad(weatherSource.HeadingDeg);
RocketParameters.LaunchInclination = deg2rad(weatherSource.InclinationDeg);
RocketParameters.LaunchRoll = deg2rad(weatherSource.LocalLaunchRollDeg);
% The plant parameter is effective constrained travel, not physical length.
RocketParameters.RailLength = weatherSource.PhysicalRailLengthM-abs( ...
    weatherSource.NozzlePositionNotebookM-weatherSource.UpperRailButtonPositionNotebookM);
RocketParameters.DryMass = airframeMass;
RocketParameters.DryCenterOfMassZ = airframeCenter+coordinateShift;
RocketParameters.DryInertia = airframeInertia;
RocketParameters.ThrustOffset = [0;0;nozzleCenter+coordinateShift];
% RocketPy's diagonal nozzle gyration approximation about the fixed dry CM.
nozzleDistanceSquared = RocketParameters.ThrustOffset(3)^2;
RocketParameters.NozzleGyration = [(nozzleRadius^2+nozzleDistanceSquared)/4; ...
    (nozzleRadius^2+nozzleDistanceSquared)/4;nozzleRadius^2/2];
RocketParameters.BodyRadius = 0.0635;
RocketParameters.ReferenceArea = pi*RocketParameters.BodyRadius^2;
RocketParameters.NoseLength = 0.55829;
RocketParameters.NoseBaseRadius = RocketParameters.BodyRadius;
RocketParameters.NoseTipZ = 1.278+coordinateShift;
RocketParameters.NoseCPFraction = 0.5; % von Karman nose CP fraction from its tip
RocketParameters.FinNumber = 4;
RocketParameters.FinRootChord = 0.120;
RocketParameters.FinTipChord = 0.060;
RocketParameters.FinSpan = 0.110;
RocketParameters.FinSweepLength = 0.060;
RocketParameters.FinLeadingEdgeZ = -1.04956+coordinateShift;
RocketParameters.FinCant = 0;
RocketParameters.FinLiftSlope2D = finLiftSlope;
RocketParameters.TailLength = 0.060;
RocketParameters.TailTopRadius = 0.0635;
RocketParameters.TailBottomRadius = 0.0435;
RocketParameters.TailTopZ = -1.194656+coordinateShift;
RocketParameters.AeroMach = [0;powered(:,1)];
RocketParameters.AeroCdPowered = [powered(1,2);powered(:,2)];
RocketParameters.AeroCdCoast = [coast(1,2);coast(:,2)];
RocketParameters.UseCdLookup = 0; % open-loop analysis uses notebook Mach/Cd
RocketParameters.DrogueLag = 1.5;
RocketParameters.DrogueCdS = 1;
RocketParameters.MainAltitudeAGL = 800;
RocketParameters.MainLag = 1.5;
RocketParameters.MainCdS = 10;

wetMass = dryMass+propellantMass;
wetCenterNotebook = (dryMass*dryCenterNotebook+propellantMass*propellantCenter)/wetMass;
dryShift = airframeMass*(airframeCenter-dryCenterNotebook)^2 + ...
    motorDryMass*(motorDryCenter-dryCenterNotebook)^2;
dryWholeInertia = airframeInertia+motorDryInertia+[dryShift;dryShift;0];
wetShift = airframeMass*(airframeCenter-wetCenterNotebook)^2 + ...
    motorDryMass*(motorDryCenter-wetCenterNotebook)^2 + ...
    propellantMass*(propellantCenter-wetCenterNotebook)^2;
wetWholeInertia = airframeInertia+motorDryInertia+propellantInertia+[wetShift;wetShift;0];
Info = struct('Notebook','getting_started.ipynb', ...
    'ExampleName','RocketPy Calisto / Cesaroni Pro75M1670', ...
    'LatitudeDeg',weatherSource.LatitudeDeg,'LongitudeDeg',weatherSource.LongitudeDeg, ...
    'LaunchElevationMSL_M',weatherSource.ElevationM, ...
    'LaunchHeadingDeg',weatherSource.HeadingDeg, ...
    'LaunchInclinationDeg',weatherSource.InclinationDeg, ...
    'LocalLaunchRollDeg',weatherSource.LocalLaunchRollDeg, ...
    'PhysicalRailLengthM',weatherSource.PhysicalRailLengthM, ...
    'EffectiveRailTravelM',RocketParameters.RailLength, ...
    'MomentumReference','Native RocketPy 1.13 implementation with reverse CM/nozzle distances', ...
    'BodyOrigin','Combined rocket and unloaded motor center of mass; +Z noseward', ...
    'CoordinateShiftM',coordinateShift,'DryCenterOfMassNotebookM',dryCenterNotebook, ...
    'WetCenterOfMassNotebookM',wetCenterNotebook, ...
    'WetCenterOfMassAtOM',wetCenterNotebook+coordinateShift, ...
    'AirframeMassKg',airframeMass,'AirframeCenterNotebookM',airframeCenter, ...
    'AirframeIntrinsicInertiaKgm2',airframeInertia, ...
    'MotorDryMassKg',motorDryMass,'MotorDryIntrinsicInertiaKgm2',motorDryInertia, ...
    'DryMassKg',dryMass,'WetMassKg',wetMass,'PropellantInitialMassKg',propellantMass, ...
    'PropellantInitialIntrinsicInertiaKgm2',propellantInertia, ...
    'DryWholeInertiaAtCM_Kgm2',dryWholeInertia,'WetWholeInertiaAtCM_Kgm2',wetWholeInertia, ...
    'MotorInstallationNotebookM',motorInstallation, ...
    'MotorDryCenterNotebookM',motorDryCenter,'PropellantCenterNotebookM',propellantCenter, ...
    'NozzlePositionNotebookM',nozzleCenter, ...
    'MotorDryCenterLocalM',motorDryCenterLocal,'PropellantCenterLocalM',propellantCenterLocal, ...
    'NozzlePositionLocalM',nozzleCenterLocal,'NozzleRadiusM',nozzleRadius,'ThroatRadiusM',throatRadius, ...
    'GrainNumber',grainNumber,'GrainDensityKgpm3',grainDensity, ...
    'GrainOuterRadiusM',grainOuterRadius,'GrainInitialInnerRadiusM',grainInitialInnerRadius, ...
    'GrainInitialHeightM',grainInitialHeight,'GrainSeparationM',grainSeparation, ...
    'GrainInitialVolumeM3',grainVolume,'GrainInitialMassKg',grainMass, ...
    'GrainCenterOffsetsM',grainCenterOffsets,'BurnDurationS',3.9, ...
    'NotebookReportedTotalImpulseNs',6026.350,'FinLiftSlope2DPerRad',finLiftSlope, ...
    'SourceFiles',struct('StaticFire',MotorStaticFireSource,'PoweredDrag',poweredSource, ...
        'CoastDrag',coastSource,'Airfoil',airfoilSource, ...
        'License',fullfile(assetDirectory,'RocketPy-LICENSE.txt')), ...
    'Caveats',{{'Intrinsic propellant inertia follows symmetric BATES bore/end regression reconstructed from the static-fire remaining mass; grain centers retain their initial pitch.', ...
        'Symmetric solid propellant has a fixed component centroid; the total rocket center moves as its mass decreases.', ...
        'The notebook does not provide calibrated airbrake drag or actuator properties; those remain separate assumptions.', ...
        'Parachute drag areas and trigger lags are imported; existing trigger sampling, inflation, attachment and sensor models remain caller settings.'}});
end

function curve = readDragCurve(filename)
assert(isfile(filename),'RocketPyCalisto:MissingDrag', ...
    'Missing example drag data: %s.',filename);
curve = readmatrix(filename,'Delimiter',',');
assert(isreal(curve) && isequal(size(curve),[200,2]) && all(isfinite(curve(:))) && ...
    curve(1,1)>0 && all(diff(curve(:,1))>0) && all(curve(:,2)>=0), ...
    'RocketPyCalisto:DragData','Example drag data must be 200 finite increasing [Mach,Cd] pairs.');
end
